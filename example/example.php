<?php

/**
 * RECIMO API 標準開發範本
 * * [步驟說明]
 * 1. 引入權限：引入 cors.php 處理跨域問題與 OPTIONS 預檢請求。
 * 2. 引入連線：引入 db_config.php 建立 $pdo 連線物件。
 * 3. 設定格式：確保瀏覽器將回傳內容解析為 JSON。
 * 4. 業務邏輯：撰寫 SQL 並透過 PDO 取得資料。
 * 5. 回傳結果：統一使用 json_encode 輸出，不夾雜任何 HTML。
 */

// ---------------------------------------------------------
// 第一步：引入 CORS 權限設定 (必須放在程式碼最上方)
// ---------------------------------------------------------
require_once '../config/cors.php';

// ---------------------------------------------------------
// 第二步：引入資料庫連線設定
// ---------------------------------------------------------
require_once '../config/db_config.php';

// ---------------------------------------------------------
// 第三步：補強設定 - 宣告回傳格式為 JSON (讓前端 Axios 自動解析)
// ---------------------------------------------------------
header("Content-Type: application/json; charset=UTF-8");

// (選填) 開發階段可以開啟錯誤顯示，方便測試。不過正式上線後建議關閉
ini_set('display_errors', 1);
error_reporting(E_ALL);

try {
    // ---------------------------------------------------------
    // 第四步：撰寫 SQL 語句
    // ---------------------------------------------------------
    $sql = "SELECT recipe_id, recipe_name, recipe_description, recipe_image_url 
            FROM recipes 
            ORDER BY recipe_id DESC 
            LIMIT 10";

    $stmt = $pdo->query($sql);

    // 取得所有資料並轉為「關聯陣列」(Associative Array)
    $recipes = $stmt->fetchAll(PDO::FETCH_ASSOC);

    // ---------------------------------------------------------
    // 第五步：輸出 JSON 結果
    // ---------------------------------------------------------
    // 這裡我們把資料封裝在一個物件裡，方便未來擴充 (例如加上分頁資訊)
    echo json_encode($recipes);
} catch (PDOException $e) {
    // ---------------------------------------------------------
    // 錯誤處理：若資料庫出錯，回傳 500 狀態碼與錯誤訊息
    // ---------------------------------------------------------
    http_response_code(500);
    echo json_encode([
        "error" => true,
        "message" => "資料庫讀取失敗：" . $e->getMessage()
    ]);
}

// 註：此處省略? >結尾標籤，為了防止後方不小心多出的空白鍵破壞 JSON 格式